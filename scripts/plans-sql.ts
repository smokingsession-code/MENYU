/**
 * Writes a migration that syncs public.plans with src/config/plans.ts.
 * Usage: npm run plans:sql
 */
import { writeFileSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { plansAsRows } from "../src/config/plans";

const MIGRATIONS = join(__dirname, "..", "supabase", "migrations");

function literal(value: unknown): string {
  if (value === null || value === undefined) return "null";
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  if (typeof value === "string") return `'${value.replace(/'/g, "''")}'`;
  return `'${JSON.stringify(value).replace(/'/g, "''")}'::jsonb`;
}

export function plansSql(): string {
  const rows = plansAsRows()
    .map(
      (r) =>
        `  (${[r.code, r.name, r.price_monthly_ugx, r.price_yearly_ugx, r.price_per_branch, r.limits, r.features, r.sort_order]
          .map(literal)
          .join(", ")})`,
    )
    .join(",\n");
  return `-- Generated by scripts/plans-sql.ts from src/config/plans.ts. Do not edit by hand.
insert into public.plans (code, name, price_monthly_ugx, price_yearly_ugx, price_per_branch, limits, features, sort_order)
values
${rows}
on conflict (code) do update set
  name = excluded.name,
  price_monthly_ugx = excluded.price_monthly_ugx,
  price_yearly_ugx = excluded.price_yearly_ugx,
  price_per_branch = excluded.price_per_branch,
  limits = excluded.limits,
  features = excluded.features,
  sort_order = excluded.sort_order;
`;
}

function main() {
  const sql = plansSql();
  const existing = readdirSync(MIGRATIONS).filter((f) => f.endsWith("_plans_sync.sql")).sort();
  const latest = existing.at(-1);
  if (latest && readFileSync(join(MIGRATIONS, latest), "utf8") === sql) {
    console.log(`Plans unchanged (${latest}).`);
    return;
  }
  const stamp = new Date().toISOString().replace(/[-:T]/g, "").slice(0, 14);
  const file = join(MIGRATIONS, `${stamp}_plans_sync.sql`);
  writeFileSync(file, sql);
  console.log(`Wrote ${file}`);
}

if (require.main === module) main();
